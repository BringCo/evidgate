"""Built-in check commands: `method: builtin:prose:absolutes draft.md`.

Why this exists: a check generated by this tool must run under the way this tool is
installed. Shelling out to `evidgate ...` breaks for the most common case -- a clone
run through ./bin/evidgate -- and produces `exit 127` with no explanation. Built-ins
are dispatched in-process, so there is no PATH to get wrong.
"""
from __future__ import annotations

import contextlib
import io
import os
import time
from typing import Callable, Dict, List, Tuple

from .evidence import Artifact, Evidence

PLUGINS: Dict[str, Dict[str, Callable]] = {}


def register(plugin: str, rules: Dict[str, Callable]) -> None:
    PLUGINS[plugin] = rules


def is_builtin(method: str) -> bool:
    return method.strip().startswith("builtin:")


def _load_default_plugins() -> None:
    if PLUGINS:
        return
    from ..plugins import prose
    # each builtin entry takes (path) and returns an exit code; prose.scan is that entry
    register("prose", {rule: (lambda path, _r=rule: prose.scan(path, _r))
                       for rule in prose.RULES})


def parse(method: str) -> Tuple[str, str, List[str]]:
    """'builtin:prose:absolutes draft.md' -> ('prose', 'absolutes', ['draft.md'])."""
    spec, _, rest = method.strip().partition(" ")
    parts = spec.split(":")
    if len(parts) != 3 or parts[0] != "builtin":
        raise ValueError(
            f"bad builtin method {method!r}; expected builtin:<plugin>:<rule> [args]"
        )
    return parts[1], parts[2], rest.split()


def dispatch(method: str, cwd: str = ".") -> Evidence:
    """Run a builtin check in-process and wrap the result as Evidence.

    cwd matters: a check declared against the project must see the project's files,
    exactly like a shell check does.
    """
    _load_default_plugins()
    plugin, rule, args = parse(method)
    started = time.strftime("%Y-%m-%dT%H:%M:%S")
    t0 = time.time()

    if plugin not in PLUGINS:
        return Evidence(method, None, "", f"unknown builtin plugin {plugin!r}", 0.0, started)
    if rule not in PLUGINS[plugin]:
        return Evidence(method, None, "", f"unknown builtin rule {rule!r}", 0.0, started)

    buf = io.StringIO()
    prev = os.getcwd()
    try:
        if cwd and os.path.isdir(cwd):
            os.chdir(cwd)
        with contextlib.redirect_stdout(buf):
            code = int(PLUGINS[plugin][rule](*args))
    except SystemExit as exc:  # a rule may call sys.exit
        code = int(exc.code or 0)
    except TypeError as exc:
        return Evidence(method, None, "", f"builtin arg error: {exc}", 0.0, started)
    except FileNotFoundError as exc:
        return Evidence(method, 2, "", f"file not found: {exc}", 0.0, started)
    finally:
        try:
            os.chdir(prev)
        except OSError:
            pass
    out = buf.getvalue()
    return Evidence(method, code, out, "", round(time.time() - t0, 3), started)


def describe(method: str, cwd: str = ".") -> str:
    """Human-readable form used by `evidgate doctor`."""
    try:
        plugin, rule, args = parse(method)
    except ValueError as exc:
        return f"BAD: {exc}"
    _load_default_plugins()
    if plugin not in PLUGINS:
        return f"BAD: unknown plugin {plugin!r} (have: {sorted(PLUGINS)})"
    if rule not in PLUGINS[plugin]:
        return f"BAD: unknown rule {rule!r} in {plugin} (have: {sorted(PLUGINS[plugin])})"
    missing = [a for a in args
               if not a.startswith("-")
               and not os.path.exists(a if os.path.isabs(a) else os.path.join(cwd, a))]
    if missing:
        return f"WARN: file not found: {', '.join(missing)}"
    return "OK"