"""artifact plugin: is the delivered thing still the thing you produced?

Derived from three rules that already govern this user's content assets:

1. one asset has exactly one source; a copy is either deleted or declared a derivative
2. a derivative is regenerated by a script, never hand-edited
3. registering at creation time is cheap; discovering later is expensive

Each rule is decidable from a manifest, so no guessing is involved.

Manifest (`artifacts.json`):

    {
      "root": ".",
      "ignore": ["*.log", "tmp/", "*.tmp"],
      "items": [
        {"path": "src/report.md",     "role": "source"},
        {"path": "build/report.html", "role": "derivative", "source": "src/report.md",
         "md5": "<hash of the artifact itself>",
         "source_md5": "<hash of the source when this derivative was generated>"},
        {"path": "draft/copy.md",     "role": "derivative", "source": "src/report.md",
         "same_as_source": true}
      ]
    }

Rules and exit codes: 0 clean, 2 blocking, 3 advisory.
  manifest  every registered path exists; recorded md5 still matches      (red)
  stale     the source changed after this derivative was generated        (yellow)
  orphan    a file on disk that the manifest never registered             (yellow)
  sync      same_as_source derivative differs from its source             (red)

`stale` compares the recorded `source_md5` with the source's hash now. It does not use
mtime: every writer (git clone, unzip, rsync) stamps "now", so comparing times says
nothing about whether the source actually changed. Measured on this repo's own example,
the mtime version flipped between 1 PASS / 2 DIFF in a working tree and 2 PASS / 1 DIFF
after a clone; the hash version is identical in both.
"""
from __future__ import annotations

import fnmatch
import hashlib
import re
import json
import os
from typing import Dict, List, Tuple

SKIP_DIRS = {".git", "__pycache__", "node_modules", ".artifacts", ".venv", ".idea"}
# the gate's own config/output is not a deliverable, so it never counts as "unregistered"
SKIP_FILES = {"evidgate.yaml", "evidgate_ledger.md", "gate_report.md"}

RULES = ("manifest", "stale", "orphan", "sync")


def _md5(path: str, normalize_newlines: bool = False) -> str:
    h = hashlib.md5()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            if normalize_newlines:
                chunk = chunk.replace(b"\\r\\n", b"\\n")
            h.update(chunk)
    return h.hexdigest()


def _root_of(data: dict, path: str) -> str:
    root = data.get("root", ".")
    if not os.path.isabs(root):
        root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(path)), root))
    return root


def _load(path: str) -> Tuple[str, List[dict], List[str]]:
    with open(path, encoding="utf-8") as fh:
        data = json.load(fh)
    return _root_of(data, path), data.get("items") or [], data.get("ignore") or []


def _abs(root: str, rel: str) -> str:
    return rel if os.path.isabs(rel) else os.path.normpath(os.path.join(root, rel))


def rule_manifest(path: str) -> List[str]:
    root, items, _ = _load(path)
    hits = []
    for it in items:
        rel = it.get("path")
        if not rel:
            hits.append("清单里有一项缺少 path")
            continue
        full = _abs(root, rel)
        if not os.path.exists(full):
            hits.append(f"登记了但不存在: {rel}")
            continue
        want = it.get("md5")
        # structural test, not a label: anything that declares a source, or is flagged
        # same_as_source, is a derivative. Relying on role= meant a manifest entry that
        # wrote `source` but forgot `role` was silently skipped (measured: empty result
        # with a deliberately wrong md5).
        is_derivative = bool(it.get("source") or it.get("same_as_source")
                             or it.get("role") == "derivative")
        if want and is_derivative:
            got = _md5(full)
            if got != want:
                # a pure line-ending difference is a checkout artefact, not an edit
                if _md5(full, normalize_newlines=True) == want:
                    continue
                hits.append(f"内容变了(手改或重跑过): {rel}  md5 {got[:8]} != 登记 {want[:8]}")
    return hits


def rule_stale(path: str) -> List[str]:
    """The source moved on and the derivative was not regenerated.

    Decided by hash, never by mtime -- see the module docstring for why.
    """
    root, items, _ = _load(path)
    hits = []
    for it in items:
        src, rel = it.get("source"), it.get("path")
        if not (src and rel):
            continue
        s = _abs(root, src)
        if not os.path.exists(s):
            hits.append(f"源不存在，派生无从核对: {rel} <- {src}")
            continue
        recorded = it.get("source_md5")
        if not recorded:
            hits.append(f"未记录 source_md5，无法判断是否过期: {rel}（重新生成后跑 artifact-stamp 记录）")
            continue
        if _md5(s) != recorded:
            hits.append(f"源已变，派生未重新生成: {rel} <- {src}")
    return hits


def rule_sync(path: str) -> List[str]:
    root, items, _ = _load(path)
    hits = []
    for it in items:
        if not it.get("same_as_source"):
            continue
        src, rel = it.get("source"), it.get("path")
        if not (src and rel):
            hits.append(f"same_as_source 缺 source/path: {it}")
            continue
        s, d = _abs(root, src), _abs(root, rel)
        if not (os.path.exists(s) and os.path.exists(d)):
            continue
        if _md5(s) != _md5(d):
            hits.append(f"派生与源不一致(违反「派生不手改」): {rel} != {src}")
    return hits


def rule_orphan(path: str, scan_dir: str = ".") -> List[str]:
    root, items, ignore = _load(path)
    patterns = [re.compile(fnmatch.translate(p)) for p in ignore]
    known = {os.path.normpath(_abs(root, it["path"])) for it in items if it.get("path")}
    known.add(os.path.normpath(os.path.abspath(path)))
    base = _abs(root, scan_dir)
    hits = []
    for dp, dn, fn in os.walk(base):
        dn[:] = [d for d in dn if d not in SKIP_DIRS]
        for f in fn:
            if f in SKIP_FILES:
                continue
            full = os.path.normpath(os.path.join(dp, f))
            rel = os.path.relpath(full, root).replace(os.sep, "/")
            if patterns and (any(r.match(rel) for r in patterns)
                             or any(r.match(f) for r in patterns)):
                continue
            if full not in known:
                hits.append(f"未登记(漏纳管): {rel}")
    return hits


def refresh(path: str) -> int:
    """Recompute the artifacts' own recorded hashes. Never touches `source_md5`.

    An earlier version also refreshed `source_md5`, which silently declared every
    derivative up to date: one `artifact-update` erased every stale item without
    regenerating anything. That is the opposite of a gate, so stamping is now a
    separate, explicit act -- see `stamp()`.
    """
    with open(path, encoding="utf-8") as fh:
        data = json.load(fh)
    root = _root_of(data, path)
    changed = 0
    for it in data.get("items") or []:
        rel = it.get("path")
        if not rel:
            continue
        # sources carry no md5: their only tracked fact is source_md5 on the derivatives,
        # and only `artifact-stamp` writes that.
        if not (it.get("source") or it.get("same_as_source") or it.get("role") == "derivative"):
            continue
        full = _abs(root, rel)
        if os.path.exists(full):
            got = _md5(full)
            if it.get("md5") != got:
                it["md5"] = got
                changed += 1
    with open(path, "w", encoding="utf-8", newline=chr(10)) as fh:
        json.dump(data, fh, ensure_ascii=False, indent=2)
        fh.write(chr(10))
    return changed


def stamp(path: str, targets: List[str]) -> int:
    """Record "this derivative was generated from the source as it is right now".

    The only writer of `source_md5`. Call it immediately after regenerating, never in
    bulk: stamping something you did not regenerate is exactly the lie that `stale`
    exists to catch.
    """
    with open(path, encoding="utf-8") as fh:
        data = json.load(fh)
    root = _root_of(data, path)
    by_path = {it.get("path"): it for it in data.get("items") or []}
    n = 0
    for t in targets:
        it = by_path.get(t)
        if it is None:
            raise SystemExit(f"{t}: 不在清单里")
        src = it.get("source")
        if not src:
            raise SystemExit(f"{t}: 清单里没有 source 字段，它不是一个派生")
        sf, df = _abs(root, src), _abs(root, t)
        if not os.path.exists(df):
            raise SystemExit(f"{t}: 文件不存在，先重新生成再盖章")
        if not os.path.exists(sf):
            raise SystemExit(f"{t}: 源 {src} 不存在")
        it["source_md5"] = _md5(sf)
        it["md5"] = _md5(df)
        n += 1
    with open(path, "w", encoding="utf-8", newline=chr(10)) as fh:
        json.dump(data, fh, ensure_ascii=False, indent=2)
        fh.write(chr(10))
    return n


def _split_args(argv: List[str]) -> Tuple[str, Dict[str, str]]:
    positional, opts = [], {}
    i = 0
    while i < len(argv):
        a = argv[i]
        if a.startswith("--"):
            opts[a[2:]] = argv[i + 1] if i + 1 < len(argv) else ""
            i += 2
        else:
            positional.append(a)
            i += 1
    return (positional[0] if positional else ""), opts


def run(rule: str, argv: List[str]) -> int:
    if rule not in RULES:
        print(f"unknown artifact rule {rule!r} (have: {RULES})")
        return 2
    path, opts = _split_args(argv)
    if not path:
        print("artifact rules need a manifest path, e.g. builtin:artifact:manifest artifacts.json")
        return 2
    if not os.path.exists(path):
        print(f"manifest not found: {path}")
        return 2

    red = {True: 2, False: 3}
    if rule == "orphan":
        hits = rule_orphan(path, opts.get("dir", "."))
        code = red[False]
    else:
        fn = {"manifest": rule_manifest, "stale": rule_stale, "sync": rule_sync}[rule]
        hits = fn(path)
        code = red[rule in ("manifest", "sync")]

    if not hits:
        print(f"[{rule}] clean")
        return 0
    limit = 30
    for h in hits[:limit]:
        print(h)
    if len(hits) > limit:
        print(f"... 另有 {len(hits) - limit} 条未列出（见台账 evidence / 收窄 --dir）")
    print(f"[{rule}] {len(hits)} finding(s)  (exit {code})")
    return code